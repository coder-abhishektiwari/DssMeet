/**
 * DssMeet Warden desktop shell (Electron).
 *
 * Security posture — this is a thin, hardened window around the built SPA:
 *  - Renderer is fully sandboxed: no Node, no arbitrary IPC surface. The only
 *    bridge is a small preload that exposes the app version and opens
 *    allowlisted https URLs in the OS browser.
 *  - UI is served from the local `app://` custom scheme (standard + secure),
 *    so the renderer never loads remote document content and localStorage
 *    lives on an isolated app origin.
 *  - Strict CSP ships inside dist/index.html (vite securityMetas plugin).
 *  - Every window.open / navigation / permission / webview attempt is denied
 *    by default; only an allowlist of our own https hosts may open externally.
 *  - DevTools, reload and refresh accelerators are disabled in production.
 */
import { app, BrowserWindow, Menu, protocol, session, shell, net, ipcMain } from 'electron';
import { autoUpdater } from 'electron-updater';
import path from 'node:path';
import fs from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DIST = path.resolve(__dirname, '..', 'dist');
const APP_ORIGIN = 'app://app';

// App icon (generated by scripts/make-icons.mjs). In dev the window takes it
// from build/; the packaged installer ships the same files as the exe icon.
const APP_ICON =
  process.platform === 'win32'
    ? path.join(__dirname, '..', 'build', 'icon.ico')
    : path.join(__dirname, '..', 'build', 'icon.png');

const isDev = process.argv.includes('--dev');
const isSmoke = process.argv.includes('--smoke');
const DEV_URL = 'http://localhost:3001';

/**
 * Hosts the renderer may hand to the OS browser. Anything else — including
 * look-alike http/deep-link URLs — is dropped without being opened.
 */
const ALLOWED_EXTERNAL_HOSTS = new Set([
  'calls.dsssolutions.in',
  'www.google.com',
  'maps.google.com',
  'google.com',
  // Update downloads are published as GitHub Release assets.
  'github.com',
  'objects.githubusercontent.com',
  'release-assets.githubusercontent.com',
]);

protocol.registerSchemesAsPrivileged([
  {
    scheme: 'app',
    privileges: {
      standard: true,
      secure: true,
      supportFetchAPI: true,
      corsEnabled: true,
      stream: true,
    },
  },
]);

/** Join a URL path under DIST, refusing any `..` escape (path traversal). */
function safeDistPath(urlPath) {
  const decoded = decodeURIComponent(urlPath);
  const resolved = path.normalize(path.join(DIST, decoded));
  if (resolved !== DIST && !resolved.startsWith(DIST + path.sep)) return null;
  return resolved;
}

async function serveAppFile(request) {
  if (request.method !== 'GET') {
    return new Response('Method Not Allowed', { status: 405 });
  }
  let urlPath = new URL(request.url).pathname;
  if (urlPath === '/' || urlPath === '') urlPath = '/index.html';

  let file = safeDistPath(urlPath);
  if (!file) return new Response('Forbidden', { status: 403 });

  try {
    const stat = await fs.stat(file);
    if (stat.isDirectory()) file = path.join(file, 'index.html');
  } catch {
    // SPA fallback for extension-less routes (react-router deep links).
    if (path.extname(urlPath)) return new Response('Not Found', { status: 404 });
    file = path.join(DIST, 'index.html');
  }

  const upstream = await net.fetch(pathToFileURL(file).toString());
  const headers = { ...Object.fromEntries(upstream.headers), 'X-Content-Type-Options': 'nosniff' };
  return new Response(upstream.body, { status: upstream.status, headers });
}

let mainWindow = null;

function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1440,
    height: 900,
    minWidth: 1024,
    minHeight: 700,
    show: false,
    backgroundColor: '#0B2240',
    ...(existsSync(APP_ICON) ? { icon: APP_ICON } : {}),
    autoHideMenuBar: true,
    title: 'DssMeet Warden',
      webPreferences: {
        contextIsolation: true,
        nodeIntegration: false,
        nodeIntegrationInWorker: false,
        nodeIntegrationInSubFrames: false,
        sandbox: true,
        webSecurity: true,
        allowRunningInsecureContent: false,
        experimentalFeatures: false,
        webviewTag: false,
        spellcheck: false,
        devTools: isDev || isSmoke,
        navigateOnDragDrop: false,
        // Minimal, validated bridge (app version + opening an allowlisted
        // https URL in the OS browser) — see electron/preload.mjs.
        preload: path.join(__dirname, 'preload.mjs'),
      },
  });

  Menu.setApplicationMenu(null);
  mainWindow.once('ready-to-show', () => mainWindow.show());

  if (isSmoke) {
    mainWindow.webContents.once('did-finish-load', () => {
      // Give React a moment to mount before checking.
      setTimeout(async () => {
        try {
          const state = await mainWindow.webContents.executeJavaScript(
            `({ mounted: !!document.getElementById('root')?.childElementCount, title: document.title, origin: location.origin })`
          );
          console.log('SMOKE_OK ' + JSON.stringify(state));
        } catch (err) {
          console.log('SMOKE_FAIL ' + err.message);
        }
        app.quit();
      }, 2000);
    });
  }

  if (isDev) {
    mainWindow.loadURL(DEV_URL);
  } else {
    mainWindow.loadURL(APP_ORIGIN + '/');
  }
  return mainWindow;
}

function hardenWebContents(contents) {
  // No popup windows, ever. Allowlisted https links open in the OS browser.
  contents.setWindowOpenHandler(({ url }) => {
    try {
      const parsed = new URL(url);
      if (parsed.protocol === 'https:' && ALLOWED_EXTERNAL_HOSTS.has(parsed.hostname)) {
        shell.openExternal(url);
      }
    } catch {
      // Malformed URL — drop silently.
    }
    return { action: 'deny' };
  });

  // The app never leaves its own origin (react-router pushState is same-document
  // and unaffected). Block link-driven navigations and all redirects.
  contents.on('will-navigate', (event, url) => {
    const allowed = isDev ? url.startsWith(DEV_URL) : url.startsWith(APP_ORIGIN + '/');
    if (!allowed) event.preventDefault();
  });
  contents.on('will-redirect', (event) => event.preventDefault());

  // Production: kill devtools / reload / refresh accelerators (no menu exists,
  // and devTools is already off — this also blocks before-input bindings).
  contents.on('before-input-event', (event, input) => {
    if (isDev || isSmoke) return;
    const mod = input.control || input.meta;
    const key = input.key.toLowerCase();
    const blocked =
      input.key === 'F12' ||
      input.key === 'F5' ||
      (mod && (key === 'r' || key === 'u' || key === 'p')) ||
      (mod && input.shiftKey && (key === 'i' || key === 'j' || key === 'c'));
    if (blocked) event.preventDefault();
  });

  // Unknown sub-window / iframe attach attempts are already impossible
  // (webviewTag off, window.open denied) — belt and braces below.
  contents.on('will-attach-webview', (event) => event.preventDefault());
}

// Renderer sandbox must be locked before any window exists.
app.enableSandbox();

// ==================== PRELOAD BRIDGE (validated, minimal) ====================
// The renderer may ask for its own version/platform and for an allowlisted
// https URL to be opened in the OS browser (the update download). Nothing
// else crosses the bridge.
ipcMain.handle('dss:app-info', () => ({
  version: app.getVersion(),
  platform: process.platform,
}));

ipcMain.handle('dss:open-external', async (_event, url) => {
  try {
    const parsed = new URL(String(url));
    if (parsed.protocol !== 'https:') return false;
    if (!ALLOWED_EXTERNAL_HOSTS.has(parsed.hostname)) return false;
    await shell.openExternal(parsed.toString());
    return true;
  } catch {
    return false;
  }
});

// ==================== AUTO UPDATE (electron-updater) ====================
// The update FEED is the GitHub Releases page (see electron-builder.yml).
// The download itself is handled by electron-updater — the renderer only
// sees the progress through the events below.
//
// In dev (unpackaged app) electron-updater cannot work — it needs the
// published app metadata. The renderer falls back to the release registry
// in that case.
const isPackaged = app.isPackaged;

autoUpdater.autoDownload = false;
autoUpdater.autoInstallOnAppQuit = true;
autoUpdater.logger = null;

function sendUpdateEvent(type, payload) {
  if (mainWindow && !mainWindow.isDestroyed()) {
    mainWindow.webContents.send('dss:update-event', { type, ...payload });
  }
}

ipcMain.handle('dss:update-check', async () => {
  if (!isPackaged) return { available: false, reason: 'dev' };
  try {
    const result = await autoUpdater.checkForUpdates();
    return {
      available: !!result?.updateInfo && result.updateInfo.version !== app.getVersion(),
      version: result?.updateInfo?.version ?? null,
      releaseNotes: result?.updateInfo?.releaseNotes ?? null,
      releaseDate: result?.updateInfo?.releaseDate ?? null,
    };
  } catch (err) {
    return { available: false, reason: String(err?.message || err) };
  }
});

ipcMain.handle('dss:update-download', async () => {
  if (!isPackaged) return { ok: false };
  try {
    await autoUpdater.downloadUpdate();
    return { ok: true };
  } catch (err) {
    return { ok: false, error: String(err?.message || err) };
  }
});

ipcMain.handle('dss:update-quit-install', async () => {
  if (!isPackaged) return { ok: false };
  // Close the window first so a restart is clean.
  setImmediate(() => {
    autoUpdater.quitAndInstall(false, true);
  });
  return { ok: true };
});

autoUpdater.on('checking-for-update', () => sendUpdateEvent('checking'));
autoUpdater.on('update-available', (info) =>
  sendUpdateEvent('available', { version: info?.version ?? null })
);
autoUpdater.on('update-not-available', () => sendUpdateEvent('not-available'));
autoUpdater.on('download-progress', (progress) =>
  sendUpdateEvent('progress', {
    percent: Math.round(progress?.percent ?? 0),
    transferred: progress?.transferred ?? 0,
    total: progress?.total ?? 0,
    bytesPerSecond: progress?.bytesPerSecond ?? 0,
  })
);
autoUpdater.on('update-downloaded', (info) =>
  sendUpdateEvent('downloaded', { version: info?.version ?? null })
);
autoUpdater.on('error', (err) =>
  sendUpdateEvent('error', { message: String(err?.message || err) })
);

// Match the installer's appId so Windows taskbar pinning/groups pick up the
// app icon instead of Electron's default.
if (process.platform === 'win32') app.setAppUserModelId('com.dssmeet.warden');

const gotLock = app.requestSingleInstanceLock();
if (!gotLock) {
  app.quit();
} else {
  app.on('second-instance', () => {
    if (mainWindow) {
      if (mainWindow.isMinimized()) mainWindow.restore();
      mainWindow.focus();
    }
  });

  app.whenReady().then(() => {
    protocol.handle('app', serveAppFile);

    // Deny every powerful browser permission (camera/mic/geo/notifications…)
    // — the warden console needs none of them.
    session.defaultSession.setPermissionRequestHandler((_contents, _permission, callback) => {
      callback(false);
    });

    app.on('web-contents-created', (_event, contents) => hardenWebContents(contents));

    createWindow();
  });
}

app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') app.quit();
});
